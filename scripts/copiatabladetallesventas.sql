BEGIN TRAN MEJORADETALLESVENTA
SELECT * 
INTO #TEMPDETALLEVENTAS
FROM DETALLEVENTA ORDER BY nVenta ASC
IF @@ERROR != 0
BEGIN
	ROLLBACK TRAN MEJORADETALLESVENTA
	PRINT 'HUBO UN ERROR AL INSERTAR EN LA TEMPORAL'
END

