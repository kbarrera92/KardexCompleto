SELECT * FROM #TEMPDETALLEVENTAS
IF @@ERROR != 0
BEGIN
	ROLLBACK TRAN MEJORADETALLESVENTA
	PRINT 'HUBO UN ERROR AL INSERTAR EN LA NUEVA TABLA'
END



COMMIT TRAN MEJORADETALLESVENTA
DROP TABLE #TEMPDETALLEVENTAS

